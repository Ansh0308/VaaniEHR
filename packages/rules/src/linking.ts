// Concept suggestions (remaining Phase 5 items, ADR-D37): a TypeScript port of the Python linker
// (apps/asr-py/app/extraction/linking.py, the reference). It suggests up to N concepts for a fact's words from the owner's
// UNREVIEWED draft list. A suggestion is only a suggestion: the doctor confirms a link; the system never does. No scores
// leave this module for the screen, no SNOMED ids exist, and only `symptom` facts can be linked.
// Matching: Unicode NFC, case-folded, punctuation replaced by a space (letters and combining marks stay), whole words.
//   exact      the whole value equals a form
//   contained  a form occurs as a run of whole words inside the value (longer form first)
//   fuzzy      a run of words as long as the form is >= 0.85 similar (forms of 4+ characters only)
// The fuzzy ratio is difflib.SequenceMatcher.ratio() reimplemented exactly (no junk, short strings); the parity file
// packages/rules/fixtures/concepts/linker-parity.json is generated by the Python linker and both test suites must match it.

export const FUZZY_MIN = 0.85;
export const FUZZY_MIN_CHARS = 4;
export const LINKABLE_TYPES: readonly string[] = ['symptom'];

export interface ConceptEntry {
  id: string;
  labels: Record<string, string[]>;
}
export interface Suggestion {
  concept_id: string;
  form: string;
  method: 'exact' | 'contained' | 'fuzzy';
  score: number;
}

export function norm(text: string): string {
  const folded = text.normalize('NFC').toLowerCase();
  let out = '';
  for (const ch of folded) out += /[\p{P}\p{S}\p{C}]/u.test(ch) ? ' ' : ch;
  return out.split(/\s+/u).filter(Boolean).join(' ');
}

const words = (text: string): string[] => norm(text).split(' ').filter(Boolean);

/** difflib.SequenceMatcher(None, a, b).ratio() for strings without junk. */
export function ratio(a: string, b: string): number {
  const A = Array.from(a);
  const B = Array.from(b);
  if (A.length + B.length === 0) return 1;
  const b2j = new Map<string, number[]>();
  B.forEach((ch, j) => {
    const list = b2j.get(ch);
    if (list) list.push(j);
    else b2j.set(ch, [j]);
  });
  const longest = (
    alo: number,
    ahi: number,
    blo: number,
    bhi: number,
  ): [number, number, number] => {
    let besti = alo;
    let bestj = blo;
    let bestsize = 0;
    let j2len = new Map<number, number>();
    for (let i = alo; i < ahi; i++) {
      const next = new Map<number, number>();
      for (const j of b2j.get(A[i] as string) ?? []) {
        if (j < blo) continue;
        if (j >= bhi) break;
        const k = (j2len.get(j - 1) ?? 0) + 1;
        next.set(j, k);
        if (k > bestsize) {
          besti = i - k + 1;
          bestj = j - k + 1;
          bestsize = k;
        }
      }
      j2len = next;
    }
    return [besti, bestj, bestsize];
  };
  let matched = 0;
  const queue: [number, number, number, number][] = [[0, A.length, 0, B.length]];
  while (queue.length > 0) {
    const [alo, ahi, blo, bhi] = queue.pop() as [number, number, number, number];
    const [i, j, k] = longest(alo, ahi, blo, bhi);
    if (k > 0) {
      matched += k;
      if (alo < i && blo < j) queue.push([alo, i, blo, j]);
      if (i + k < ahi && j + k < bhi) queue.push([i + k, ahi, j + k, bhi]);
    }
  }
  return (2 * matched) / (A.length + B.length);
}

function match(
  value: string[],
  form: string[],
): { method: Suggestion['method']; score: number } | null {
  const k = form.length;
  if (value.length === k && value.every((w, i) => w === form[i]))
    return { method: 'exact', score: 1 };
  for (let i = 0; i + k <= value.length; i++) {
    if (value.slice(i, i + k).every((w, n) => w === form[n]))
      return { method: 'contained', score: 1 };
  }
  const target = form.join(' ');
  if (Array.from(target).length < FUZZY_MIN_CHARS) return null;
  let best = 0;
  for (let i = 0; i < Math.max(1, value.length - k + 1); i++) {
    best = Math.max(best, ratio(value.slice(i, i + k).join(' '), target));
  }
  return best >= FUZZY_MIN ? { method: 'fuzzy', score: best } : null;
}

const TIER = { exact: 0, contained: 1, fuzzy: 2 } as const;
const round3 = (n: number): number => Math.round(n * 1000) / 1000;

export class ConceptLinker {
  private readonly forms: { id: string; form: string; words: string[] }[] = [];
  constructor(concepts: ConceptEntry[]) {
    for (const c of concepts) {
      for (const list of Object.values(c.labels)) {
        for (const form of list) {
          const w = words(form);
          if (w.length > 0) this.forms.push({ id: c.id, form, words: w });
        }
      }
    }
  }

  suggest(factType: string, value: string, limit = 3): Suggestion[] {
    if (!LINKABLE_TYPES.includes(factType)) return [];
    const w = words(value);
    if (w.length === 0) return [];
    type Key = [number, number, number, string];
    const best = new Map<string, { key: Key; s: Suggestion }>();
    for (const f of this.forms) {
      const hit = match(w, f.words);
      if (!hit) continue;
      const score = round3(hit.score);
      const key: Key = [TIER[hit.method], -score, -f.words.join(' ').length, f.id];
      const prior = best.get(f.id);
      if (!prior || compare(key, prior.key) < 0) {
        best.set(f.id, { key, s: { concept_id: f.id, form: f.form, method: hit.method, score } });
      }
    }
    return [...best.values()]
      .sort((a, b) => compare(a.key, b.key))
      .slice(0, limit)
      .map((x) => x.s);
  }
}

function compare(a: [number, number, number, string], b: [number, number, number, string]): number {
  for (let i = 0; i < 3; i++) {
    const d = (a[i] as number) - (b[i] as number);
    if (d !== 0) return d;
  }
  return a[3] < b[3] ? -1 : a[3] > b[3] ? 1 : 0;
}
