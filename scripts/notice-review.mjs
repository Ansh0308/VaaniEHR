// Writes docs/NOTICE_REVIEW.md (Phase 12B Run 2): the exact Gujarati notice strings a native speaker must check, taken straight from
// the sources so the list cannot drift. Run through tsx: `npx tsx scripts/notice-review.mjs` .
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  FACT_LABEL,
  FREQUENCY,
  P,
  PHRASE_TABLE_VERSION,
  STOP_WORDS,
  TEMPLATE_BODY_EN,
  TEMPLATE_BODY_GU,
  TEMPLATE_NAME,
} from '../apps/api-node/src/whatsapp/phrases.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const json = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const cell = (v) => String(v).replaceAll('|', '\\|').replaceAll('\n', ' <br> ');
const rows = (list) => list.map((r) => `| ${r.map(cell).join(' | ')} |`).join('\n');

const consentEn = json('apps/api-node/src/consent/notices/v0.1/en.json');
const consentGu = json('apps/api-node/src/consent/notices/v0.1/gu.json');
const privacyEn = json('apps/web/src/i18n/locales/en/privacy.json');
const privacyGu = json('apps/web/src/i18n/locales/gu/privacy.json');
const patientsEn = json('apps/web/src/i18n/locales/en/patients.json');
const patientsGu = json('apps/web/src/i18n/locales/gu/patients.json');
const shellEn = json('apps/web/src/i18n/locales/en/shell.json');
const shellGu = json('apps/web/src/i18n/locales/gu/shell.json');

const countStrings = (o) =>
  typeof o === 'string'
    ? 1
    : o && typeof o === 'object'
      ? Object.values(o).reduce((n, v) => n + countStrings(v), 0)
      : 0;
const guDir = join(ROOT, 'apps/web/src/i18n/locales/gu');
const guStrings = readdirSync(guDir)
  .filter((f) => f.endsWith('.json'))
  .reduce((n, f) => n + countStrings(JSON.parse(readFileSync(join(guDir, f), 'utf8'))), 0);

const consentRows = [
  ['notice title', consentEn.title, consentGu.title],
  ['notice body', consentEn.body, consentGu.body],
  ...Object.keys(consentEn.scopes).flatMap((s) => [
    [`${s}: label`, consentEn.scopes[s].label, consentGu.scopes[s].label],
    [`${s}: description`, consentEn.scopes[s].description, consentGu.scopes[s].description],
  ]),
];
const phraseRows = [
  ...Object.entries(P).map(([k, v]) => [`phrase: ${k}`, v.en, v.gu]),
  ...Object.entries(FACT_LABEL).map(([k, v]) => [`fact label: ${k}`, v.en, v.gu]),
  ...Object.entries(FREQUENCY).map(([k, v]) => [`frequency: ${k}`, v.en, v.gu]),
  ...STOP_WORDS.map((w) => [
    `stop word`,
    /\P{ASCII}/u.test(w) ? '(Gujarati word for stop)' : 'the standard English word',
    w,
  ]),
];
const pick = (en, gu, keys) =>
  keys.map((k) => [
    k,
    k.split('.').reduce((o, x) => o?.[x], en),
    k.split('.').reduce((o, x) => o?.[x], gu),
  ]);
const privacyRows = pick(privacyEn, privacyGu, [
  'title',
  'intro',
  'rules.title',
  'rules.removes',
  'rules.keeps',
  'rules.open',
  'complete.title',
  'complete.body',
  'complete.confirm',
  'complete.done',
  'refuse.title',
  'refuse.body',
  'queue.ownOnly',
  'errors.conflict',
  'errors.open',
  'errors.other',
]).filter((r) => r[1] !== undefined);
const abhaRows = pick(patientsEn, patientsGu, [
  'abha.intro',
  'abha.notice.mock',
  'abha.notice.sandbox',
  'abha.enter.attest',
  'abha.enter.hint.mock',
  'abha.enter.hint.sandbox',
  'abha.result.stored',
  'abha.error.rejected.body',
]);
const bannerRows = pick(shellEn, shellGu, ['banner.text', 'banner.configError']);

const out = `# Gujarati notice review checklist (Phase 12B Run 2, ADR-D45)

> Generated by \`npx tsx scripts/notice-review.mjs\` from the sources named below, so the strings here are the exact ones in the product. **Every Gujarati string in this list is UNREVIEWED.** The legal wording of the consent notice is also a **placeholder**: whether it is legally sufficient is for my guide / institution, not for the Gujarati reviewer. Nothing here is legal advice. Nobody other than the owner should be shown these notices as if they were final.

## How to review

Give this file to a native Gujarati speaker (ideally also someone who has used a clinic). For each row they check:

1. **Meaning**: the Gujarati says what the English next to it says, and nothing more or less.
2. **Natural wording**: it is what a person in Gujarat would say or read, not a literal word-for-word copy; polite and plain, not harsh or frightening.
3. **Medical words**: the symptom, medicine and frequency words are the ones patients use (for example "twice a day"), not textbook terms.
4. **Script and numbers**: Gujarati script and Gujarati or Western digits used the same way throughout; English drug names stay in Latin script.
5. **Length**: the WhatsApp phrases fit the template (one-line variables, no line breaks inside a variable).
6. **Consent notice**: the person understands what they are agreeing to; the three choices are clear and separate; withdrawing is easy to understand. (Legal sufficiency: not the reviewer's job.)
7. **Warnings**: nothing in the notices gives medical advice.

Mark each row **OK**, **change** (write the replacement) or **unclear**, then fill the sign-off table at the end. Changes are made by editing the source file named in each section and adding a **new** consent notice version (published versions are immutable) or bumping the phrase table version.

## 1. Consent notice, version 0.1 (placeholder text)

Appears on: the consent page PG-05 (\`/consult/:id/consent\`, read to or shown to the patient by staff), the stored consent events (notice version and language), and \`GET /api/v1/consent/notice\`. Source: \`apps/api-node/src/consent/notices/v0.1/{en,gu}.json\`. Status: \`${consentGu.status}\`, \`needsReview: ${consentGu.needsReview}\`.

| Item | English | Gujarati |
|---|---|---|
${rows(consentRows)}

## 2. WhatsApp summary phrases (phrase table ${PHRASE_TABLE_VERSION}, template \`${TEMPLATE_NAME}\`)

Appear on: the approval page PG-11 (\`/consult/:id/summary\`, the Gujarati preview with an approximate English back-translation) and in the message sent to the patient. The system writes **only** these fixed phrases; the warning signs and the follow-up are typed by the doctor. Source: \`apps/api-node/src/whatsapp/phrases.ts\`. See also docs/WHATSAPP_SUBMISSION.md.

| Item | English meaning | Gujarati |
|---|---|---|
${rows(phraseRows)}

Template body as it would be submitted to Meta (the numbered parts are filled in per patient):

\`\`\`
${TEMPLATE_BODY_GU}
\`\`\`

English side (for the doctor's back-translation only):

\`\`\`
${TEMPLATE_BODY_EN}
\`\`\`

## 3. Data erasure page (PG-20)

Appears on: \`/privacy/requests\`. Source: \`apps/web/src/i18n/locales/{en,gu}/privacy.json\`. The line that says whether a signed record must be kept is deliberately marked "to be confirmed"; the reviewer checks the Gujarati says the same, not that it is legally right.

| Key | English | Gujarati |
|---|---|---|
${rows(privacyRows)}

## 4. ABHA check page (PG-04)

Appears on: \`/patients/:id/abha\`. Source: \`apps/web/src/i18n/locales/{en,gu}/patients.json\` (\`abha\`). The words MOCK and SANDBOX stay in Latin script on purpose so they cannot be missed.

| Key | English | Gujarati |
|---|---|---|
${rows(abhaRows)}

## 5. The prototype banner

Appears on: every page. Source: \`apps/web/src/i18n/locales/{en,gu}/shell.json\`.

| Key | English | Gujarati |
|---|---|---|
${rows(bannerRows)}

## 6. Everything else in Gujarati

All other Gujarati screen text (\`apps/web/src/i18n/locales/gu/*.json\`) is also unreviewed and is marked on screen with "Needs review by a Gujarati speaker" (\`NeedsReview\`). The app has ${guStrings} Gujarati screen strings; review the sections above first, because they are the ones a patient sees or hears.

## Sign-off

| Section | Reviewer name | Date | Verdict (OK / changes made / unclear) | Notes | Signature |
|---|---|---|---|---|---|
| 1 Consent notice 0.1 (language only) | | | | | |
| 1 Consent notice 0.1 (legal sufficiency) | *to be checked by my guide / institution* | | | | |
| 2 WhatsApp phrases | | | | | |
| 3 Erasure page | | | | | |
| 4 ABHA page | | | | | |
| 5 Prototype banner | | | | | |
| 6 Remaining screens | | | | | |

When a section is signed off, set \`needsReview\` to false in the consent notice file (new version), and record the reviewer and date in docs/OWNER_ACTIONS.md.
`;

writeFileSync(join(ROOT, 'docs', 'NOTICE_REVIEW.md'), out);
console.log('wrote docs/NOTICE_REVIEW.md (format it with prettier)');
